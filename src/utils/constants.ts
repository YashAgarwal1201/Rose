export const MS_PER_WEEK = MS_PER_DAY * DAYS_PER_WEEK;
export const MS_PER_MONTH = MS_PER_DAY * DAYS_PER_MONTH;
export const MS_PER_YEAR = MS_PER_DAY * DAYS_PER_YEAR;
